String bookNameFor(String book, String language) =>
    language == 'pt' ? _ptBook[book] ?? book : book;

String referenceFor(String reference, String language) {
  final space = reference.indexOf(' ');
  if (space < 0) return reference;
  return '${bookNameFor(reference.substring(0, space), language)}'
      '${reference.substring(space)}';
}
